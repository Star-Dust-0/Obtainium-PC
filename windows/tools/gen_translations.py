#!/usr/bin/env python3
"""Generates windows/ObtainiumPC/Services/Localization/LocTranslations.g.cs
from upstream assets/translations/*.json (GPL-3.0, preserved in this fork).

Keys are upstream en.json string VALUES - the port's gettext-style English
literals (Loc.T uses the English literal as the key). Nested easy_localization
plural dicts flatten to the "other" form; plural inflection itself is not
ported (disclosed in PARITY.md). Entries identical to English are omitted.

Language list + display names mirror lib/main.dart supportedLocales.
"""
import json
import os

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
TRANS = os.path.join(ROOT, "assets", "translations")
OUT = os.path.join(ROOT, "windows", "ObtainiumPC", "Services", "Localization", "LocTranslations.g.cs")

# (tag, file, display name) from lib/main.dart supportedLocales, order kept.
LANGS = [
    ("en", "en.json", "English"),
    ("bn", "bn.json", "বাংলা"),
    ("zh-Hant-TW", "zh-Hant-TW.json", "臺灣話"),
    ("zh", "zh.json", "简体中文"),
    ("it", "it.json", "Italiano"),
    ("ja", "ja.json", "日本語"),
    ("hu", "hu.json", "Magyar"),
    ("de", "de.json", "Deutsch"),
    ("fa", "fa.json", "فارسی"),
    ("fr", "fr.json", "Français"),
    ("es", "es.json", "Español"),
    ("pl", "pl.json", "Polski"),
    ("ru", "ru.json", "Русский"),
    ("bs", "bs.json", "Bosanski"),
    ("pt-BR", "pt-BR.json", "Brasileiro"),
    ("pt", "pt.json", "Português"),
    ("cs", "cs.json", "Česky"),
    ("sv", "sv.json", "Svenska"),
    ("nl", "nl.json", "Nederlands"),
    ("vi", "vi.json", "Tiếng Việt"),
    ("tr", "tr.json", "Türkçe"),
    ("uk", "uk.json", "Українська"),
    ("da", "da.json", "Dansk"),
    ("en-EO", "en-EO.json", "Esperanto"),
    ("id", "id.json", "Bahasa Indonesia"),
    ("ko", "ko.json", "한국어"),
    ("ca", "ca.json", "Català"),
    ("ar", "ar.json", "العربية"),
    ("ml", "ml.json", "മലയാളം"),
    ("gl", "gl.json", "Galego"),
]

def flatten(d):
    """key -> display string (plural dicts take their 'other' form)."""
    out = {}
    for k, v in d.items():
        if isinstance(v, str):
            out[k] = v
        elif isinstance(v, dict):
            other = v.get("other")
            if isinstance(other, str):
                out[k] = other
    return out

def cs(s):
    return (s.replace("\\", "\\\\").replace('"', '\\"')
             .replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
             .replace("$", "\\u0024").replace("{", "\\u007b").replace("}", "\\u007d"))
    # ^ keep generated literals free of $ and {} so no C# interpolation or
    #   format-string confusion can arise in consuming code paths.

def load(name):
    with open(os.path.join(TRANS, name), encoding="utf-8") as f:
        return json.load(f)

en_flat = flatten(load("en.json"))
en_value_to_key = {}
for k, v in en_flat.items():
    en_value_to_key.setdefault(v, k)

parts = []
parts.append("// <auto-generated> by windows/tools/gen_translations.py from upstream")
parts.append("// assets/translations/*.json (GPL-3.0, preserved in this fork).")
parts.append("// Do not edit by hand; rerun the generator instead.")
parts.append("using System.Collections.Generic;")
parts.append("")
parts.append("namespace ObtainiumPC.Services.Localization;")
parts.append("")
parts.append("public static class LocTranslations")
parts.append("{")
parts.append("    /// lib/main.dart supportedLocales (order and display names kept).")
parts.append("    public static readonly (string Tag, string Name)[] SupportedLanguages =")
parts.append("    {")
for tag, _f, name in LANGS:
    parts.append(f'        ("{tag}", "{cs(name)}"),')
parts.append("    };")
parts.append("")

fields = []
for tag, fname, _name in LANGS:
    if tag == "en":
        continue
    lang_flat = flatten(load(fname))
    entries = {}
    for k, v in lang_flat.items():
        en_v = en_flat.get(k)
        if en_v and v and v != en_v:
            entries[en_v] = v
    if not entries:
        continue
    field = "L_" + tag.replace("-", "_")
    fields.append((tag, field))
    parts.append(f"    private static readonly Dictionary<string, string> {field} = new()")
    parts.append("    {")
    for en_v in sorted(entries):
        parts.append(f'        ["{cs(en_v)}"] = "{cs(entries[en_v])}",')
    parts.append("    };")
    parts.append("")

parts.append("    public static readonly IReadOnlyDictionary<string, IReadOnlyDictionary<string, string>> ByLang")
parts.append("        = new Dictionary<string, IReadOnlyDictionary<string, string>>")
parts.append("    {")
for tag, field in fields:
    parts.append(f'        ["{tag}"] = {field},')
parts.append("    };")
parts.append("}")

with open(OUT, "w", encoding="utf-8") as f:
    f.write("\n".join(parts) + "\n")
print("wrote", OUT, "langs:", len(fields), "entries:", sum(len(flatten(load(fn))) and 0 or 0 for _t, fn, _n in LANGS))

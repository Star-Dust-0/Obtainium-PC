def flatten(d):
    """key -> display string (plural dicts take their 'other' form)."""
    out = {}
    for k, v in d.items():
        if isinstance(v, str):
            out[k] = v
        elif isinstance(v, dict):
            other = v.get("other")
            if isinstance(other, str):
                out[k] = other
    return out

def cs(s):
    return (s.replace("\\", "\\\\").replace('"', '\\"')
             .replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
             .replace("$", "\\u0024").replace("{", "\\u007b").replace("}", "\\u007d"))
    # ^ keep generated literals free of $ and {} so no C# interpolation or
    #   format-string confusion can arise in consuming code paths.

def load(name):
    with open(os.path.join(TRANS, name), encoding="utf-8") as f:
        return json.load(f)

en_flat = flatten(load("en.json"))
en_value_to_key = {}
for k, v in en_flat.items():
    en_value_to_key.setdefault(v, k)

parts = []
parts.append("// <auto-generated> by windows/tools/gen_translations.py from upstream")
parts.append("// assets/translations/*.json (GPL-3.0, preserved in this fork).")
parts.append("// Do not edit by hand; rerun the generator instead.")
parts.append("using System.Collections.Generic;")
parts.append("")
parts.append("namespace ObtainiumPC.Services.Localization;")
parts.append("")
parts.append("public static class LocTranslations")
parts.append("{")
parts.append("    /// lib/main.dart supportedLocales (order and display names kept).")
parts.append("    public static readonly (string Tag, string Name)[] SupportedLanguages =")
parts.append("    {")
for tag, _f, name in LANGS:
    parts.append(f'        ("{tag}", "{cs(name)}"),')
parts.append("    };")
parts.append("")

fields = []
for tag, fname, _name in LANGS:
    if tag == "en":
        continue
    lang_flat = flatten(load(fname))
    entries = {}
    for k, v in lang_flat.items():
        en_v = en_flat.get(k)
        if en_v and v and v != en_v:
            entries[en_v] = v
    tip = BACK_TOOLTIP.get(tag)
    if tip and tip != "Back":
        entries["Back"] = tip
    if not entries:
        continue
    field = "L_" + tag.replace("-", "_")
    fields.append((tag, field))
    parts.append(f"    private static readonly Dictionary<string, string> {field} = new()")
    parts.append("    {")
    for en_v in sorted(entries):
        parts.append(f'        ["{cs(en_v)}"] = "{cs(entries[en_v])}",')
    parts.append("    };")
    parts.append("")

parts.append("    public static readonly IReadOnlyDictionary<string, IReadOnlyDictionary<string, string>> ByLang")
parts.append("        = new Dictionary<string, IReadOnlyDictionary<string, string>>")
parts.append("    {")
for tag, field in fields:
    parts.append(f'        ["{tag}"] = {field},')
parts.append("    };")
parts.append("}")

# ---- plural tables ----
# For every en.json key whose value is a plural dict, emit per-language form
# maps keyed by the English "other" VALUE (the port's gettext literal).
en_raw = load("en.json")
plural_keys = {k: v for k, v in en_raw.items() if isinstance(v, dict) and "other" in v}

pparts = []
pparts.append("// <auto-generated> by windows/tools/gen_translations.py from upstream")
pparts.append("// assets/translations/*.json plural dicts (easy_localization forms).")
pparts.append("// Keyed by the English \"other\" value; forms selected by PluralRules.")
pparts.append("using System.Collections.Generic;")
pparts.append("")
pparts.append("namespace ObtainiumPC.Services.Localization;")
pparts.append("")
pparts.append("public static class LocPlurals")
pparts.append("{")
pfields = []
for tag, fname, _name in LANGS:  # en included: English one/other selection needs it
    lang_raw = load(fname)
    entries = {}
    for k, forms in plural_keys.items():
        en_other = forms["other"]
        if not isinstance(en_other, str):
            continue
        lv = lang_raw.get(k)
        if isinstance(lv, dict):
            lang_forms = {fk: fv for fk, fv in lv.items() if isinstance(fv, str)}
            if lang_forms:
                entries[en_other] = lang_forms
    if not entries:
        continue
    field = "P_" + tag.replace("-", "_")
    pfields.append((tag, field))
    pparts.append(f"    private static readonly Dictionary<string, Dictionary<string, string>> {field} = new()")
    pparts.append("    {")
    for en_other in sorted(entries):
        pparts.append(f'        ["{cs(en_other)}"] = new Dictionary<string, string>')
        pparts.append("        {")
        for fk in sorted(entries[en_other]):
            pparts.append(f'            ["{fk}"] = "{cs(entries[en_other][fk])}",')
        pparts.append("        },")
    pparts.append("    };")
    pparts.append("")
pparts.append("    public static readonly IReadOnlyDictionary<string, IReadOnlyDictionary<string, Dictionary<string, string>>> ByLang")
pparts.append("        = new Dictionary<string, IReadOnlyDictionary<string, Dictionary<string, string>>>")
pparts.append("    {")
for tag, field in pfields:
    pparts.append(f'        ["{tag}"] = {field},')
pparts.append("    };")
pparts.append("}")

pout = os.path.join(ROOT, "windows", "ObtainiumPC", "Services", "Localization", "LocPlurals.g.cs")
with open(pout, "w", encoding="utf-8") as f:
    f.write("\n".join(pparts) + "\n")
print("wrote", pout, "langs:", len(pfields), "plural keys:", len(plural_keys))

with open(OUT, "w", encoding="utf-8") as f:
    f.write("\n".join(parts) + "\n")
print("wrote", OUT, "langs:", len(fields), "entries:", sum(len(flatten(load(fn))) and 0 or 0 for _t, fn, _n in LANGS))

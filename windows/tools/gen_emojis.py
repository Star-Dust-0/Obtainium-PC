#!/usr/bin/env python3
"""Generates windows/ObtainiumPC/Services/EmojiTable.g.cs from the Dart
markdown package's emojis.dart (lib/src/emojis.dart in dart-lang/markdown,
BSD-3, itself generated from https://api.github.com/emojis). Upstream renders
:shortcode: emoji in changelogs via md.EmojiSyntax(); this is the exact table
that syntax resolves against."""
import re
import sys
import urllib.request

URL = "https://raw.githubusercontent.com/dart-lang/markdown/master/lib/src/emojis.dart"
OUT = "windows/ObtainiumPC/Services/EmojiTable.g.cs"

text = urllib.request.urlopen(URL, timeout=30).read().decode("utf-8")
entries = re.findall(r"^  '([^']+)': '(.*?)',$", text, re.M)
assert len(entries) > 1500, f"suspiciously few emoji entries: {len(entries)}"

def cs(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')

lines = [
    "// <auto-generated> by windows/tools/gen_emojis.py from lib/src/emojis.dart in",
    "// dart-lang/markdown (BSD-3, (c) the Dart project authors; the table is itself",
    "// generated from https://api.github.com/emojis). Do not edit by hand.",
    "using System.Collections.Generic;",
    "",
    "namespace ObtainiumPC.Services;",
    "",
    "public static class EmojiTable",
    "{",
    "    public static readonly IReadOnlyDictionary<string, string> Emojis =",
    "        new Dictionary<string, string>",
    "    {",
]
for name, emoji in entries:
    lines.append(f'        ["{name}"] = "{emoji}",')
lines.append("    };")
lines.append("}")
with open(OUT, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", OUT, "entries:", len(entries))
